// Builds ui-icons.js from tools/icons/*.svg (Lucide, ISC licence). Run: node tools/build-icons.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, 'icons'), out = {};
for (const f of fs.readdirSync(dir)) {
  if (!f.endsWith('.svg')) continue;
  const s = fs.readFileSync(path.join(dir, f), 'utf8');
  const inner = s.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  out[f.replace('.svg', '')] = inner;
}
const js = `/* Generated by tools/build-icons.js — Lucide icons (ISC). */
(function(){
var P = ${JSON.stringify(out)};
window.Icon = function(name, size, cls){
  var p = P[name]; if (!p) return '';
  size = size || 18;
  return '<svg class="ui-i' + (cls ? ' ' + cls : '') + '" style="width:' + size + 'px;height:' + size + 'px" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + p + '</svg>';
};
window.Icon.has = function(n){ return !!P[n]; };
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'ui-icons.js'), js);
console.log(Object.keys(out).length + ' icons');
