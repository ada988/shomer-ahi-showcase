#!/bin/sh
# Regenerates showcase/host.ported.js from beta/app.js (run from the repo root).
# Needs acorn + acorn-walk:  ACORN=/path/to/acorn ACORN_WALK=/path/to/acorn-walk sh showcase/tools/port.sh
# seeds.txt lists the entry points; closure.js adds every beta top-level dependency not provided elsewhere.
NAMES=$(node showcase/tools/closure.js $(cat showcase/tools/seeds.txt) | node -e "console.log(JSON.parse(require('fs').readFileSync(0,'utf8')).port.join(' '))")
{ echo "/* Functions ported verbatim from beta/app.js (generated by showcase/tools/port.sh). Firebase paths are inert in the showcase. */"
  node showcase/tools/port-from-beta.js $NAMES
} > showcase/host.ported.js
